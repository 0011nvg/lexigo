import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const base=process.env.LEXIGO_URL||'http://127.0.0.1:4173/';
const errors=[];
for(const viewport of [{width:1280,height:850},{width:390,height:844}]){
 const page=await browser.newPage({viewport});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 await page.getByRole('link',{name:/кабинеты/i}).waitFor();
 await page.getByRole('link',{name:/кабинеты/i}).click();
 await page.waitForURL('**/cabinet.html*');
 assert.equal(await page.getByRole('tab').count(),3);
 assert.equal(await page.getByRole('tabpanel',{name:/учитель/i}).isVisible(),true);
 const options=await page.locator('#assignSection option').count();
 assert.ok(options>=1,'Real Spotlight sections should populate');
 await page.locator('#assignClass').selectOption('2А');
 await page.locator('#assignSection').selectOption('1');
 await page.locator('#assignDate').fill('2026-12-10');
 await page.getByRole('button',{name:'Назначить тренировку'}).click();
 assert.match(await page.locator('#assignStatus').innerText(),/добавлено/);
 await page.getByRole('tab',{name:/ученик/i}).click();
 assert.ok(await page.locator('#studentTasks .task').count()>=2);
 const before=Number(await page.locator('#parentCompleted').innerText());
 await page.locator('#studentTasks [data-complete]').last().click();
 await page.getByRole('tab',{name:/родитель/i}).click();
 assert.equal(Number(await page.locator('#parentCompleted').innerText()),before+1);
 await page.reload();
 await page.getByRole('tab',{name:/родитель/i}).click();
 assert.equal(Number(await page.locator('#parentCompleted').innerText()),before+1,'Demo tasks must survive reload');
 await page.getByRole('tab',{name:/учитель/i}).click();
 await page.getByRole('button',{name:'Сбросить демоданные'}).click();
 assert.equal(await page.locator('#teacherTasks .task').count(),2);
 await page.getByRole('tab',{name:/ученик/i}).click();
 assert.equal(await page.locator('#studentTasks .task').count(),1);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2);
 assert.equal(overflow,false,'Dashboard must fit viewport '+viewport.width);
 await page.close();
}
await browser.close();
assert.deepEqual(errors,[]);
console.log('PASS: dashboard roles, real Spotlight sections, assignment flow, parent visibility, persistence, reset, desktop/mobile');
